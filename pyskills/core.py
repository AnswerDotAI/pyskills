    mod_dir.mkdir(parents=True, exist_ok=True)
    for i in range(len(parts)-1): (sd / Path(*parts[:i+1]) / '__init__.py').touch()
    (mod_dir / f'{parts[-1]}.py').write_text(f'"""{docstr}"""\n{code}')
    enable_pyskill(name)

