def delete_pyskill(name):
    "Delete pyskill `name` module files and dist-info"
    disable_pyskill(name)
    sd = pyskills_dir()
    parts = name.split('.')
    mod_file = sd / Path(*parts[:-1]) / f'{parts[-1]}.py' if len(parts) > 1 else sd / f'{parts[-1]}.py'
    if mod_file.exists(): mod_file.unlink()
